"""Build harm/static/icons.js: the Lucide icons HaRM uses, as plain data (no build step at run time).

    python3 scripts/build-icons.py [path/to/lucide-react]   # default: ../zomello/node_modules/lucide-react

Lucide (https://lucide.dev) is ISC licensed; the license is copied into harm/static/vendor/LUCIDE-LICENSE.
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "zomello" / "node_modules" / "lucide-react"
NAMES = """house list-checks monitor layers server package hammer network radar key-round map-pin cable library
share-2 scroll-text settings circle-help camera bot download trash-2 notebook-pen smartphone tablet clipboard tag
upload external-link plug pin globe snowflake menu qr-code wrench lock pencil flag star chevron-down chevron-right
compass shield printer hard-drive video moon sun sun-moon arrow-left-right undo-2 boxes play square rotate-cw plus
search x check triangle-alert circle-check info copy log-out sparkles scan-line file-down list cpu memory-stick
router wifi cloud-download folder-input eye eye-off link refresh-cw circle sliders-horizontal""".split()


def parse_all(names):
    """Read each icon's data object with Node (the files are JS object literals, not JSON)."""
    import subprocess
    js = r"""
const fs = require('fs'), path = require('path');
const dir = process.argv[1], out = {};
for (const n of process.argv.slice(2)) {
  let file = n, text, m;
  for (let hop = 0; hop < 4; hop++) {  // aliases (e.g. circle-help) re-export another icon's file
    text = fs.readFileSync(path.join(dir, file + '.mjs'), 'utf8');
    m = text.match(/const __iconData = (\{[\s\S]*?\n\});/);
    if (m) break;
    const alias = text.match(/from ['"]\.\/([\w-]+)\.mjs['"]/);
    if (!alias) break;
    file = alias[1];
  }
  if (!m) throw new Error('cannot read ' + n);
  const data = Function('return ' + m[1])();
  out[n] = data.node.map(([tag, attrs]) => { const a = { ...attrs }; delete a.key; return [tag, a]; });
}
process.stdout.write(JSON.stringify(out));
"""
    p = subprocess.run(["node", "-e", js, str(SRC / "dist" / "esm" / "icons"), *names], capture_output=True, text=True)
    if p.returncode:
        raise SystemExit(p.stderr)
    return json.loads(p.stdout)


icons = parse_all(NAMES)
out = ROOT / "harm" / "static" / "icons.js"
out.write_text("/* Lucide icons (https://lucide.dev, ISC license, see vendor/LUCIDE-LICENSE). Generated by scripts/build-icons.py. */\n"
               "const LUCIDE = " + json.dumps(icons, separators=(",", ":")) + ";\n")
shutil.copy(SRC / "LICENSE", ROOT / "harm" / "static" / "vendor" / "LUCIDE-LICENSE")
print(f"{len(icons)} icons, {out.stat().st_size // 1024} KB -> {out.relative_to(ROOT)}")
