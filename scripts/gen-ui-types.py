"""Write ui/src/api/entities.ts: a TypeScript type for each kind of record, made from harm/models.py.

    python3 scripts/gen-ui-types.py           # write it
    python3 scripts/gen-ui-types.py --check   # fail if it's out of date (CI runs this)

The server's field list stays the one source: a field renamed there is a build error in the interface.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from harm.models import ENTITIES  # noqa: E402

OUT = ROOT / "ui" / "src" / "api" / "entities.ts"
TS = {"text": "string", "date": "string", "int": "number", "real": "number", "bool": "boolean"}


def type_name(entity: str) -> str:
    singular = {"device_slots": "DeviceSlot", "build_items": "BuildItem", "credentials": "Credential",
                "connections": "Connection", "clusters": "Cluster", "notes": "Note", "actions": "Action"}
    if entity in singular:
        return singular[entity]
    name = entity[:-1] if entity.endswith("s") else entity
    return "".join(p.capitalize() for p in name.split("_"))


def joined(select: str) -> list[str]:
    """The extra columns a list adds with "AS name" (device_name, rack_count…)."""
    seen = []
    for name in re.findall(r"\bAS\s+([a-z_][a-z0-9_]*)", select, re.I):
        if name not in seen and name.lower() not in ("t", "p", "l", "d", "r", "c"):
            seen.append(name)
    return seen


def joined_type(name: str) -> str:
    if re.search(r"(_count|_u|_n|_gb|_w|^n|_price|_total|ips?_count)$", name):
        return "number | null"
    if name.startswith(("has_", "is_")):
        return "boolean | number | null"
    return "string | null"


def render() -> str:
    out = ["/* Generated by scripts/gen-ui-types.py from harm/models.py. Don't edit by hand. */", ""]
    names = []
    for entity, spec in ENTITIES.items():
        t = type_name(entity)
        names.append((entity, t))
        out.append(f"export interface {t} {{")
        out.append("  id: number;")
        for field, (ftype, required) in spec["fields"].items():
            ts = "number" if ftype.startswith("fk:") else TS.get(ftype, "string")
            if ftype == "bool":
                ts = "boolean | number"
            out.append(f"  {field}: {ts}{'' if required and ftype != 'bool' else ' | null'};")
        fields = set(spec["fields"])
        for extra in joined(spec.get("select", "")):
            if extra not in fields:
                out.append(f"  {extra}?: {joined_type(extra)};")
        out.append("  created_at?: string;")
        out.append("  updated_at?: string;")
        out.append("}")
        out.append("")
    out.append("export interface EntityTypes {")
    out.extend(f"  {e}: {t};" for e, t in names)
    out.append("}")
    out.append("export type EntityName = keyof EntityTypes;")
    out.append(f"export const ENTITY_NAMES: EntityName[] = [{', '.join(repr(e) for e, _ in names)}];")
    return "\n".join(out) + "\n"


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit("ui/src/api/entities.ts is out of date: run python3 scripts/gen-ui-types.py")
        print("ui/src/api/entities.ts is up to date")
        return
    OUT.write_text(text)
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
